// Rebuild distribution notices from installed npm packages and locked Rust sources.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const records = new Map();
const missing = [];
function add(name, version, directory, license) {
  const id = `${name}@${version}`;
  if (records.has(id)) return;
  const files = fs
    .readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && /^(licen[sc]e|copying|notice)([.-]|$)/i.test(entry.name));
  const texts = files.map((entry) => fs.readFileSync(path.join(directory, entry.name), 'utf8'));
  const fallback = name.startsWith('@esbuild/')
    ? 'node_modules/esbuild/LICENSE.md'
    : name.startsWith('@rollup/rollup-')
      ? 'node_modules/rollup/LICENSE.md'
      : name === 'tauri-plugin'
        ? 'third-party-licenses/tauri-plugin-LICENSE.txt'
        : name === 'webview2-com'
          ? 'src-tauri/vendor/webview2-com-sys/LICENSE'
          : name === 'webview2-com-macros'
            ? 'third-party-licenses/webview2-com-macros-LICENSE.txt'
            : name === 'alloc-stdlib'
              ? 'third-party-licenses/alloc-stdlib-LICENSE.txt'
              : name === 'selectors'
                ? 'third-party-licenses/selectors-LICENSE.txt'
                : null;
  if (!texts.length && fallback) texts.push(fs.readFileSync(path.join(root, fallback), 'utf8'));
  if (!texts.length) missing.push(id);
  records.set(
    id,
    `${id}\nLicense expression: ${typeof license === 'string' ? license : JSON.stringify(license || 'not specified')}\n\n${texts.join('\n\n') || 'See the upstream package for its license terms.'}`
  );
}
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json')));
for (const [location, record] of Object.entries(lock.packages)) {
  if (!location || !location.startsWith('node_modules/')) continue;
  const directory = path.join(root, location);
  if (!fs.existsSync(path.join(directory, 'package.json'))) continue;
  const manifest = JSON.parse(fs.readFileSync(path.join(directory, 'package.json')));
  add(manifest.name, manifest.version, directory, manifest.license || record.license);
}
for (const target of ['x86_64-pc-windows-gnullvm', 'aarch64-pc-windows-gnullvm']) {
  const metadata = JSON.parse(
    execFileSync(
      'cargo',
      [
        'metadata',
        '--locked',
        '--format-version',
        '1',
        '--manifest-path',
        'src-tauri/Cargo.toml',
        '--filter-platform',
        target,
      ],
      { cwd: root, maxBuffer: 20 * 1024 * 1024 }
    )
  );
  const nodes = new Map(metadata.resolve.nodes.map((node) => [node.id, node]));
  const reachable = new Set();
  const queue = [metadata.resolve.root];
  while (queue.length) {
    const id = queue.pop();
    if (reachable.has(id)) continue;
    reachable.add(id);
    queue.push(...(nodes.get(id)?.dependencies || []));
  }
  for (const record of metadata.packages) {
    if (record.name === 'yaoc' || !reachable.has(record.id)) continue;
    add(record.name, record.version, path.dirname(record.manifest_path), record.license);
  }
}
const vendor = path.join(root, 'src-tauri/vendor/webview2-com-sys');
for (const name of ['MICROSOFT-WEBVIEW2-LICENSE.txt', 'MICROSOFT-WEBVIEW2-NOTICE.txt'])
  records.set(name, fs.readFileSync(path.join(vendor, name), 'utf8'));
const banner =
  'YAOC third-party license notices\n\nGenerated by npm run notices from installed dependencies and the locked Windows Rust dependency graph. Includes development/build dependencies where available. Third-party terms remain applicable independently of the YAOC project license.\n\n';
fs.writeFileSync(
  path.join(root, 'THIRD_PARTY_LICENSES.txt'),
  banner +
    [...records.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([, text]) => text)
      .join('\n\n' + '='.repeat(78) + '\n\n') +
    '\n'
);
console.log(`Wrote notices for ${records.size} packages/files.`);
if (missing.length)
  throw new Error(
    'Packages without a top-level license file (required before redistribution): ' +
      missing.sort().join(', ')
  );
